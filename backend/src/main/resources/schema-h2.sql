-- 面试工坊 · 数据基座（H2）
--
-- 对齐关系（LingChat → 本项目）：
--   role                  → interviewer         角色卡
--   （无，本项目扩展）     → user_profile        用户身份（LingChat 把身份写在角色卡里）
--   story_config.yaml     → interview_script    面试流程模板
--   Chapters/{/*}.yaml    → interview_chapter   流程阶段
--   save + running_script → interview_session   场次 + 运行状态
--   line                  → interview_message   台词
--
-- 换 MySQL：IDENTITY → AUTO_INCREMENT，CLOB → TEXT，BOOLEAN → TINYINT。
--
-- 幂等约束（重要）：本文件在每次启动时都会执行（spring.sql.init.mode=always），
-- 因此这里不允许出现 DROP TABLE——否则重启即清库。建表一律 IF NOT EXISTS，
-- 种子数据见 data-h2.sql / scripts-h2.sql 的 MERGE INTO。

-- ============ 角色卡（对齐 role）============
CREATE TABLE IF NOT EXISTS interviewer (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(32)  NOT NULL UNIQUE,
  name             VARCHAR(64)  NOT NULL,
  subtitle         VARCHAR(64),
  card_title       VARCHAR(128),
  card_info        CLOB,
  persona_prompt   CLOB         NOT NULL,
  example_dialogue CLOB,
  thinking_message VARCHAR(128),
  avatar_mode      VARCHAR(16)  DEFAULT 'image',
  scale            DOUBLE       DEFAULT 1.0,
  offset_x         DOUBLE       DEFAULT 0,
  offset_y         DOUBLE       DEFAULT 0,
  bubble_top       INT          DEFAULT 5,
  bubble_left      INT          DEFAULT 25,
  user_alias       VARCHAR(64),
  user_alias_subtitle VARCHAR(64),
  display_role     VARCHAR(64),
  opening          VARCHAR(512),
  follow_up        INT          DEFAULT 2,
  speed            INT          DEFAULT 1,
  sort_order       INT          DEFAULT 0,
  enabled          BOOLEAN      DEFAULT TRUE,
  created_at       TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- ============ 用户身份（本项目扩展）============
-- LingChat 没有独立用户表，身份散落在各角色卡的 user_name / system_prompt 里，
-- 这里归一化成单行表，字段语义与其「以下是我的设定」段一致。
CREATE TABLE IF NOT EXISTS user_profile (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nickname       VARCHAR(64)  NOT NULL,
  signature      VARCHAR(128),
  job_target     VARCHAR(32),
  school         VARCHAR(128),
  major          VARCHAR(128),
  grade          VARCHAR(32),
  student_no     VARCHAR(32),
  resume_summary CLOB,
  created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ============ 面试流程模板（对齐 story_config.yaml）============
CREATE TABLE IF NOT EXISTS interview_script (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            VARCHAR(64)  NOT NULL UNIQUE,
  script_name     VARCHAR(255) NOT NULL,
  intro_chapter   VARCHAR(255) NOT NULL,
  description     CLOB,
  recommand_start VARCHAR(255),
  interviewer_id  BIGINT,
  order_num       INT          DEFAULT 0,
  trigger_mode    VARCHAR(32)  DEFAULT 'manual',
  job_code        VARCHAR(32),
  level           VARCHAR(32),
  company_style   VARCHAR(64),
  script_settings CLOB,
  enabled         BOOLEAN      DEFAULT TRUE,
  created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_script_iv FOREIGN KEY (interviewer_id) REFERENCES interviewer(id)
);

-- ============ 流程阶段（对齐 Chapters/{Chapter}/{file}.yaml）============
-- events 为 JSON 数组，元素结构照搬剧本事件：
-- ai_dialogue / input / narration / free_dialogue / chapter_end / modify_character / background / music / sound
CREATE TABLE IF NOT EXISTS interview_chapter (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  script_id BIGINT       NOT NULL,
  code      VARCHAR(64)  NOT NULL,
  name      VARCHAR(255) NOT NULL,
  order_num INT          DEFAULT 0,
  events    CLOB         NOT NULL,
  events_backup CLOB,
  CONSTRAINT fk_chap_script FOREIGN KEY (script_id) REFERENCES interview_script(id),
  CONSTRAINT uq_chap_code   UNIQUE (script_id, code)
);

-- ============ 场次 + 运行状态（对齐 save + running_script）============
CREATE TABLE IF NOT EXISTS interview_session (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           VARCHAR(255) NOT NULL,
  user_id         BIGINT       NOT NULL,
  interviewer_id  BIGINT       NOT NULL,
  script_id       BIGINT,
  job_code        VARCHAR(32)  NOT NULL,
  kps             VARCHAR(512),
  status          VARCHAR(16)  DEFAULT 'running',
  score           INT,
  current_chapter VARCHAR(255),
  event_sequence  INT          DEFAULT 0,
  variable_info   CLOB,
  started_at      TIMESTAMP,
  ended_at        TIMESTAMP,
  created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  -- 试玩场次（对应 LingChat 试玩用的临时 GameStatus，本项目落成一行独立场次）
  preview         BOOLEAN      DEFAULT FALSE,
  -- 在场角色（对齐 game_status.present_role_ids）：逗号分隔的「NPC」role_id
  -- （= interviewer.id）。注意：原版容器里只装 NPC，从不装玩家 0
  -- （见 game_status.rs:752 onstage_role 的调用点全部传 NPC id），
  -- 所以 shouldActivate 的「> 1」= 至少两个面试官在场，单人面试不激活。
  present_role_ids VARCHAR(256),
  CONSTRAINT fk_sess_user   FOREIGN KEY (user_id) REFERENCES user_profile(id),
  CONSTRAINT fk_sess_iv     FOREIGN KEY (interviewer_id) REFERENCES interviewer(id),
  CONSTRAINT fk_sess_script FOREIGN KEY (script_id) REFERENCES interview_script(id)
);

-- ============ 在场角色好感度（对齐 AffectionVector 落档）============
-- 原版存在角色卡 + 存档里；本项目角色卡是 interviewer（全局），
-- 好感度却是"这一局"的状态，所以按场次单独存一份。
CREATE TABLE IF NOT EXISTS session_affection (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id BIGINT       NOT NULL,
  role_id    INT          NOT NULL,
  fondness   INT          DEFAULT 10,
  trust      INT          DEFAULT 5,
  intimacy   INT          DEFAULT 0,
  rapport    INT          DEFAULT 5,
  interest   INT          DEFAULT 15,
  longing    INT          DEFAULT 0,
  updated_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_affection UNIQUE (session_id, role_id),
  CONSTRAINT fk_aff_sess FOREIGN KEY (session_id) REFERENCES interview_session(id)
);

-- 老库补列（幂等）：schema 每次启动都执行，CREATE TABLE IF NOT EXISTS 不会给已存在的表加列
ALTER TABLE interview_session ADD COLUMN IF NOT EXISTS preview BOOLEAN DEFAULT FALSE;
ALTER TABLE interview_session ADD COLUMN IF NOT EXISTS present_role_ids VARCHAR(256);

-- ============ 台词（对齐 line）============
CREATE TABLE IF NOT EXISTS interview_message (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id        BIGINT      NOT NULL,
  seq               INT         NOT NULL,
  role              VARCHAR(16) NOT NULL,
  content           CLOB        NOT NULL,
  original_tag      VARCHAR(64),
  predicted_emotion VARCHAR(32),
  action            CLOB,
  msg_type          VARCHAR(16) DEFAULT 'text',
  stage_code        VARCHAR(64),
  -- 对齐 line.sender_role_id：0 = 玩家，N = 角色 id，NULL = 旁白 / system
  sender_role_id    INT,
  -- 对齐 line.identity_id：玩家说的是哪个身份（换身份后历史里并存多个），非玩家行留 NULL
  identity_id       VARCHAR(64),
  -- 对齐 line.display_name：这一句在历史里显示成谁说的（玩家行必填，旁白/系统留 NULL）
  display_name      VARCHAR(64),
  tokens            INT,
  created_at        TIMESTAMP   DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_msg_sess FOREIGN KEY (session_id) REFERENCES interview_session(id)
);

-- ============ 玩家身份卡（对齐 player_identity）============
-- 原版是「文件是真源、本表只做索引」，本项目没有身份卡目录，表即真源。
-- 为什么要有一张独立的身份表：换身份后历史里会并存多个身份说的台词，
-- 只靠 role=user 分不清谁说的，必须能按 identity_id 反查名字（见 MemoryBuilder）。
CREATE TABLE IF NOT EXISTS player_identity (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identity_id VARCHAR(64) NOT NULL UNIQUE,
  name       VARCHAR(64)  NOT NULL,
  subtitle   VARCHAR(128),
  prompt     CLOB,
  avatar     VARCHAR(255),
  -- 我对各个对象的出厂关系，JSON 对象：{"ai:<角色code>": "...", "me:<身份id>": "..."}
  relations  CLOB,
  is_current BOOLEAN      DEFAULT FALSE,
  updated_at TIMESTAMP    DEFAULT CURRENT_TIMESTAMP
);

-- ============ 设置项覆盖值（规格 B4-BE §1.5）============
-- 对齐原版 settings.json：扁平 key-value，一行一个点号 key（llm.temperature 这种），
-- 不是「一个大 JSON 字段」。没有行 = 用后端注册表里的默认值（默认值只有一份真相源）。
CREATE TABLE IF NOT EXISTS user_settings (
  config_key   VARCHAR(64)   PRIMARY KEY,
  config_value VARCHAR(2048) NOT NULL,
  updated_at   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP
);

-- ============ 增量列（已有库补列）============
-- CREATE TABLE IF NOT EXISTS 只在表不存在时建表，对已存在的库不会补列；
-- 因此新增列除了写进上面的建表语句，还必须在这里单独 ALTER 一遍。
-- 先停后端再重启，H2 文件库才不会被旧进程锁住。
ALTER TABLE interview_message ADD COLUMN IF NOT EXISTS sender_role_id INT;
-- 玩家身份解耦（对齐 line.identity_id / line.display_name）：
-- 玩家行一律带名字，多身份并存时才分得清谁说的；旁白/系统行仍走裸内容。
ALTER TABLE interview_message ADD COLUMN IF NOT EXISTS identity_id  VARCHAR(64);
ALTER TABLE interview_message ADD COLUMN IF NOT EXISTS display_name VARCHAR(64);
ALTER TABLE interview_script  ADD COLUMN IF NOT EXISTS characters CLOB;
-- 剧本编辑器：覆盖前留最近一份备份（对齐原版 <章节目录>.yaml.bak 的语义）
ALTER TABLE interview_chapter ADD COLUMN IF NOT EXISTS events_backup CLOB;

-- ============ 剧本编辑器 AI 助手 · 会话（规格 E7a1，对齐 skill_agent_conversation）============
-- 对应原版 crates/ling-chat-main/src/db/entities/skill_agent_conversation.rs：
-- 只记录创建时绑定的剧本 key，不存剧本内容快照。
CREATE TABLE IF NOT EXISTS skill_agent_conversation (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title      VARCHAR(128),
  script_key VARCHAR(64),
  created_at TIMESTAMP,
  updated_at TIMESTAMP
);

-- ============ 剧本编辑器 AI 助手 · 消息（规格 E7a1，对齐 skill_agent_message）============
-- OpenAI 消息格式：tool_calls 存序列化后的 JSON 字符串，content 为空时存 NULL。
CREATE TABLE IF NOT EXISTS skill_agent_message (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation_id   BIGINT      NOT NULL,
  role              VARCHAR(16) NOT NULL,
  content           CLOB,
  reasoning         CLOB,
  prompt_tokens     BIGINT,
  completion_tokens BIGINT,
  cached_tokens     BIGINT,
  tool_calls        CLOB,
  tool_call_id      VARCHAR(64),
  created_at        TIMESTAMP,
  CONSTRAINT fk_agent_msg_conv FOREIGN KEY (conversation_id) REFERENCES skill_agent_conversation(id)
);
