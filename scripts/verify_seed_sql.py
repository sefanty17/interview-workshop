"""用 SQLite 等价执行 H2 脚本，验证 schema + 种子数据 + 剧本引用完整性。

不做业务断言，只回答三个问题：
  1. 这些 SQL 拿去 H2 跑会不会报错
  2. 剧本里的 next_chapter 是否都指向存在的章节
  3. 事件类型是否都在剧本引擎支持的范围内
"""
import json
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.stdout.reconfigure(encoding="utf-8")

schema = (ROOT / "data/schema/schema-h2.sql").read_text(encoding="utf-8")
seed = (ROOT / "data/seed/data-h2.sql").read_text(encoding="utf-8")
scripts_sql = (ROOT / "data/seed/scripts-h2.sql").read_text(encoding="utf-8")

# H2 → SQLite 方言等价替换
schema = schema.replace("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "INTEGER PRIMARY KEY AUTOINCREMENT")
schema = schema.replace("CLOB", "TEXT").replace("DOUBLE", "REAL")
schema = schema.replace("BOOLEAN", "INTEGER").replace("TIMESTAMP", "TEXT")
schema = re.sub(r"--.*", "", schema)

conn = sqlite3.connect(":memory:")
conn.executescript(schema)
conn.executescript(seed)
conn.executescript(scripts_sql)

print("=== 表 ===")
for (name,) in conn.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite%' ORDER BY name"):
    n = conn.execute(f"SELECT COUNT(*) FROM {name}").fetchone()[0]
    print(f"  {name:22} {n:>3} 行")

print("\n=== 剧本 ===")
rows = conn.execute("""
  SELECT s.code, s.script_name, i.code, s.job_code,
         (SELECT COUNT(*) FROM interview_chapter c WHERE c.script_id = s.id)
  FROM interview_script s LEFT JOIN interviewer i ON i.id = s.interviewer_id
  ORDER BY s.order_num
""").fetchall()
for code, name, iv, job, nchap in rows:
    print(f"  {code:20} {name:22} 面试官={iv:9} 岗位={job:9} 章节={nchap}")

print("\n=== 引用完整性 ===")
errors = []
EVENT_TYPES = {
    "ai_dialogue", "input", "narration", "free_dialogue", "chapter_end",
    "modify_character", "background", "background_effect", "music", "sound",
    "ambient", "present_pic", "choice", "dialog", "player", "set_variable",
    "achievement", "script_end",
}
for sid, scode, intro in conn.execute("SELECT id, code, intro_chapter FROM interview_script").fetchall():
    chapters = {}
    for cid, ccode, events_json in conn.execute(
        "SELECT id, code, events FROM interview_chapter WHERE script_id = ?", (sid,)
    ):
        chapters[ccode] = json.loads(events_json)

    if intro not in chapters:
        errors.append(f"{scode}: intro_chapter '{intro}' 不存在")

    for ccode, events in chapters.items():
        for idx, ev in enumerate(events):
            etype = ev.get("type")
            if etype not in EVENT_TYPES:
                errors.append(f"{scode}/{ccode}[{idx}]: 未知事件类型 {etype}")
            if etype != "chapter_end":
                continue
            end_type = ev.get("end_type", "linear")
            if end_type == "linear":
                target = ev.get("next_chapter")
                if target and target != "end" and target not in chapters:
                    errors.append(f"{scode}/{ccode}: next_chapter '{target}' 不存在")
            elif end_type == "ai_judged":
                for opt in ev.get("options", []):
                    name = opt.get("name")
                    if not name:
                        errors.append(f"{scode}/{ccode}: ai_judged 选项缺 name")
                    elif name not in chapters and name != "end":
                        errors.append(f"{scode}/{ccode}: ai_judged 选项 '{name}' 不存在")
            elif end_type == "branching":
                for opt in ev.get("options", []):
                    nxt = opt.get("next")
                    if nxt and nxt != "end" and nxt not in chapters:
                        errors.append(f"{scode}/{ccode}: branching 分支 '{nxt}' 不存在")
            else:
                errors.append(f"{scode}/{ccode}: 未知 end_type {end_type}")

if errors:
    print("  发现", len(errors), "个问题：")
    for e in errors:
        print("   ✗", e)
    sys.exit(1)
print("  ✓ 全部通过（intro / next_chapter / ai_judged / branching / 事件类型）")

print("\n=== 外键链路冒烟 ===")
conn.execute(
    "INSERT INTO interview_session (title,user_id,interviewer_id,script_id,job_code,current_chapter) "
    "VALUES ('测试面试',1,1,1,'java','intro')"
)
conn.execute(
    "INSERT INTO interview_message (session_id,seq,role,content,original_tag,predicted_emotion,stage_code) "
    "VALUES (1,1,'assistant','你好','冷淡','平静','intro')"
)
print(" ", conn.execute("""
  SELECT s.title, i.name, sc.script_name, m.content, m.original_tag, m.predicted_emotion
  FROM interview_message m
  JOIN interview_session s ON s.id = m.session_id
  JOIN interviewer i ON i.id = s.interviewer_id
  JOIN interview_script sc ON sc.id = s.script_id
""").fetchone())

print("\n全脚本执行通过")
